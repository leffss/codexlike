/**
 * 任务内容列宽度类（票 05「容器分档宽度」，宽度边界见 ADR 0011）：
 * 消息流、头部与输入区共用同一基准列宽度类；输入卡片自 2026-11-19 起
 * 在基准列内左右各外扩 12px（比消息正文列宽一点，见 MessageComposer）。
 *
 * 断点基准是任务容器（WorkspacePage 中栏的 `@container/task`）而非浏览器视口：
 * 应用侧栏开合改变容器宽度时按档位分档响应；右侧面板（规范与技能 / 改动）是
 * 容器内的兄弟节点，开合不改变容器宽度，不会触发断点切换导致内容列跳宽。
 *
 * 三档（上限 2026-11-22 应用户「正文与输入框调宽一点」诉求各上移一档，
 * 断点与留白结构不变）：
 * - 基础档（容器 <864px）：内容列全宽，不设上限；
 * - 容器 ≥864px：收窄留白（calc(100% - 6rem)）且上限 max-w-5xl（1024px）；
 * - 容器 ≥1280px：留白加大（calc(100% - 12rem)）且上限 max-w-7xl（1280px）。
 *
 * 宽度变化不做过渡动画（避免拖拽 / 面板开合时反复触发消息测高）。
 */
export const TASK_CONTENT_WIDTH_CLASS =
  "mx-auto w-full @min-[864px]/task:w-[calc(100%_-_6rem)] @min-[864px]/task:max-w-5xl @min-[1280px]/task:w-[calc(100%_-_12rem)] @min-[1280px]/task:max-w-7xl";
